/** Reader-facing fallback content. Corpus prose is deliberately not pasted here:
 * the LLM receives retrieved evidence separately and must apply its conditions. */
export interface RelationshipReadingInput {
  serviceKey: string
  category: string
  title: string
  itemKey?: string
  note?: string
  analysis: SajuAnalysis
  partnerAnalysis?: SajuAnalysis
  relationship?: string
  concern?: string
  signals?: Record<string, string | undefined>
}

export type RelationshipState = 'boundary' | 'unsafe' | 'stable' | 'uncertain' | 'concern'

export function relationshipState(input: Pick<RelationshipReadingInput, 'concern' | 'signals' | 'relationship'>): RelationshipState {
  const withoutNegatedBoundary = (value: string) => value
    .replace(/(?:차단|연락\s*거부|폭력|협박|강요)(?:은|는|이|가)?\s*(?:없(?:음|어요|다|고)?|안 했(?:음|어요)?)/g, '')
    .replace(/차단(?:한 적(?:은|이)?\s*없|(?:을|이)?\s*(?:풀렸|풀었|해제됐|해제했))/g, '')
    .replace(/차단(?:당할까|될까|할까|하면|될지|당한\s*(?:건지|것인지)|인지\s*모르)/g, '')
  const text = withoutNegatedBoundary([input.concern, ...Object.values(input.signals ?? {})].filter(Boolean).join(' '))
  const boundaryText = withoutNegatedBoundary([input.relationship, text].filter(Boolean).join(' '))
  if (/폭력|협박|강요/.test(boundaryText)) return 'unsafe'
  if (/차단(?:했|된|됨|되어|당했|상태|\s*중)|(?:^|\s)차단(?:\s|$|[.,])|연락.{0,8}(?:하지\s*말|원하지\s*않|싫)|연락\s*거부|선을\s*그었|접촉\s*금지/.test(boundaryText)) return 'boundary'
  if (/(?:갈등|문제|불편|불안|변화|다툼|싸움).{0,5}(?:없|않)|(?:서로|관계가|현재).{0,8}(?:편안|안정|만족)|잘\s*지내/.test(text)
    && !/하지만|그런데|반복.*(?:취소|거짓말)|폭언/.test(text)) return 'stable'
  if (!text.trim() || /^(?:모름|모르겠|잘\s*모르|특별히\s*없|미입력)/.test(text.trim())) return 'uncertain'
  return 'concern'
}

