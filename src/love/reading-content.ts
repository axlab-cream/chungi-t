function chooseLens(input: RelationshipReadingInput): LensKey {
  const text = `${input.itemKey ?? ''} ${input.title}`
  if (/자미두수|ziwei/.test(text)) return 'ziwei'
  if (/^(?:비견|겁재|식신|상관|편재|정재|편관|정관|편인|정인):/.test(input.title)) return 'symbolic'
  if (/^(?:천간|지지|오행|띠[·/궁]|부부궁|배우자궁)/.test(input.title)) return 'symbolic'
  if (/거부|멈춰|지켜야 할 선|선을 지|경계|boundary|line.cross|avoid.tone|정리각/.test(text)) return 'boundary'
  if (/화해|회복.*대화|reconciliation|repair.sentence|사과/.test(text)) return 'repair'
  if (/케미 한 줄|우리 둘 케미|연애 가능성|연애 모드/.test(text)) return 'reciprocity'
  if (/카톡|메시지|한 문장|액션 한 줄|질문|말하는|꺼내는 문장|question|conversation.mission/.test(text)) return 'question'
  if (/돈|소비|금전|money|resource.split/.test(text)) return 'money'
  if (/가족|family/.test(text)) return 'family'
  if (/동거|집안일|생활 습관|루틴|주거|공간|휴식 방식|daily|real.life|현실 생활/.test(text)) return 'daily'
  if (/외도|바람|유혹|환승|SNS|sns|social|flirt|외부|관심받|attention.enjoy|전애인|ex.return/.test(text)) return 'social'
  if (/차단|재회|reunion|다시.*연결|old.some/.test(text)) return 'reunion'
  if (/불안|집착|자존감|촉|추측|과몰입|anxiety|feeling|checking.urge|one.beat/.test(text)) return 'anxiety'
  if (/갈등|싸움|다툼|오해|충돌|방어|소통.*장애|conflict|collision|defense|competition/.test(text)) return 'conflict'
  if (/소모|피로|지치|회복|쉬어|혼자|거리.*미션|rest|energy.drain|distance.mission|independence/.test(text)) return 'rest'
  if (/결혼|프러포즈|상견례|marriage|wedding/.test(text) && !/시기|타이밍|월|올해|운|timing|year/.test(text)) return 'marriage'
  if (/약속|책임|신뢰|안정감|trust|promise|commitment|steady|long.term/.test(text)) return 'trust'
  if (/월별|월운|일진|올해|세운|대운|시기|타이밍|택일|오늘|timing|year|month|today/.test(text)) return 'timing'
  if (/속도|직진|고백|공식화|전환|거리|pace|stage|slow|serious/.test(text)) return 'pace'
  if (/표현|말투|감정.*방식|스킨십|expression|tone|affection/.test(text)) return 'expression'
  if (/답장|연락|contact|reply/.test(text)) return 'contact'
  if (/변화|변곡|권태|줄어|식은|change|boredom|cold|temperature|entry|middle|late/.test(text)) return 'change'
  if (/도화|홍염|끌림|설렘|첫인상|매력|attraction|spark|charm/.test(text)) return 'attraction'
  if (/만남|경로|소개|새 인연|meeting|connection/.test(text)) return 'meeting'
  if (/오행|일간|일지|지지|띠|십성|비견|겁재|식신|상관|편재|정재|편관|정관|편인|정인|symbol|element|stem|branch/.test(text)) return 'symbolic'
  if (/선택|결론|라벨|카드|지수|레벨|패키|판정|각|decision|result|quest|notice/.test(text)) return 'decision'
  return 'reciprocity'
}

function pillarReading(value: string): string {
  return [...value].map((char) => STEM_KO[char as keyof typeof STEM_KO] ?? BRANCH_KO[char as keyof typeof BRANCH_KO] ?? char).join('')
}

