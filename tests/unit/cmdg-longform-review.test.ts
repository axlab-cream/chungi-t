  assert.match(editorial, /\['condition', '관계의 실제 조건'/)
  assert.match(editorial, /\['condition', '현재 계획의 실제 조건'/)
  assert.doesNotMatch(editorial, /currentRole|currentEvaluation|currentEnergy|currentReward|newRole|newEvaluation|newEnergy/)
  assert.match(editorial, /추가 정보 입력/)
  assert.match(editorial, /저장하거나 전송하지 않습니다/)
