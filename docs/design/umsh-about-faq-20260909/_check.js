class Component extends DCLogic {
  constructor(props) {
    super(props);
    // 첫 항목은 열린 상태로 시작한다. 처음 오신 분이 구조를 바로 보게 하려는 것이고,
    // 실제 구현에서도 첫 항목에 open 을 주는 형태를 그대로 쓴다.
    this.state = { service: 'wedding', step: '1', faq: 'f1' };
  }

  currentService() {
    const svc = SERVICES.find((s) => s.id === this.state.service) || SERVICES[0];
    return {
      title: svc.title,
      badge: svc.badge,
      volume: svc.volume,
      detail: svc.detail,
      href: svc.href,
      toc: svc.toc.map((name) => ({ name })),
    };
  }

  renderVals() {
    const pick = (current, id, key) => () => this.setState({ [key]: current === id ? '' : id });

    return {
      services: SERVICES.map((svc) => {
        const on = this.state.service === svc.id;
        return {
          title: svc.title,
          tagline: svc.tagline,
          price: svc.price,
          volume: svc.volume,
          badge: svc.badge,
          id: svc.id,
          family: svc.family,
          pick: on ? 'is-pick' : '',
          dot: on ? 'is-active' : '',
          select: () => this.setState({ service: svc.id }),
        };
      }),
      current: this.currentService(),
      steps: STEPS.map((step) => {
        const open = this.state.step === step.num;
        return {
          num: step.num,
          title: step.title,
          summary: step.summary,
          detail: step.detail,
          tip: step.tip,
          cta: step.cta,
          open,
          frame: open ? 'shell-on' : '',
          spin: open ? 'rotate(180deg)' : 'rotate(0deg)',
          toggle: pick(this.state.step, step.num, 'step'),
        };
      }),
      faqs: FAQS.map((f) => {
        const open = this.state.faq === f.id;
        return {
          q: f.q,
          a: f.a,
          cta: f.cta,
          open,
          frame: open ? 'shell-on' : '',
          spin: open ? 'rotate(180deg)' : 'rotate(0deg)',
          toggle: pick(this.state.faq, f.id, 'faq'),
        };
      }),
    };
  }
}
